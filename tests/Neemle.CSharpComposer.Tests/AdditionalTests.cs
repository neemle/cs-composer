namespace Neemle.CSharpComposer.Tests;
public sealed class AdditionalTests
{
    [Fact] public void Optional_header_and_document_nullable_have_explicit_option_precedence()
    {
        var doc=Cs.Document().Header("// generated by the example\r\n// stable header").Nullable(NullableMode.Enable).Class("C").End().Build();
        Assert.StartsWith("// generated by the example\n// stable header\n\n#nullable enable\n\n",doc.Render());
        Assert.DoesNotContain("#nullable",doc.Render(new RenderOptions{Nullable=NullableMode.Omit}));
        Assert.Contains("#nullable disable",doc.Render(new RenderOptions{Nullable=NullableMode.Disable}));
        Assert.Throws<ArgumentException>(()=>doc.Render(new RenderOptions{Nullable=(NullableMode)99}));
        Assert.Throws<ArgumentException>(()=>doc.Render(new RenderOptions{NamespaceStyle=(NamespaceStyle)99}));
        Assert.Throws<ArgumentException>(()=>doc.Render(new RenderOptions{Indent=null!}));
    }

    [Fact] public void Nested_declarations_and_remaining_member_forms_compile()
    {
        var b=Cs.Document().Namespace("Example").AddRange(new[]{new CsTypeDeclaration(TypeKind.Class,"Empty")});
        b.Class("Outer").Internal()
            .Struct("S").End().Record("R").End().RecordClass("RC").End().RecordStruct("RS").End().Interface("I").End().Enum("E").EnumMember("One").End()
            .Constructor().Parameter(new CsParameter(Cs.Int,"i"){Default=Cs.Literal(0)}).RawBody("// constructor").End()
            .Method(Cs.Void,"Hook").Protected().Virtual().Body(Cs.Return()).End()
            .Method(Cs.Int,"Echo").Public().Parameter<int>("i").Expression(Cs.Id("i")).End()
            .Field<int>("Hidden").Public().New().End()
            .Event("System.Action","Changed").Initialize(Cs.RawExpression("delegate { }")).End()
            .Method(Cs.Void,"Native").Static().Extern().Attribute(Cs.Attribute("System.Runtime.InteropServices.DllImport",Cs.Arg(Cs.String("example")))).End()
            .End();
        CsDocument document=b; Assert.Equal(document.Render(),b.Render());
        Assert.Equal(6,document.FindType("Outer")!.Types.Count());
    }

    [Fact] public void Type_and_expression_conveniences_keep_intent_and_operand_precedence()
    {
        Assert.Equal(CsType.Boolean,Cs.Bool); Assert.Equal(CsType.Void,Cs.Void);
        Assert.Equal(Cs.Type("List").Generic(Cs.Int),Cs.Generic("List",Cs.Int));
        Assert.Equal(Cs.Int.Nullable(),Cs.Nullable(Cs.Int)); Assert.Equal(Cs.Int.Array(2),Cs.Array(Cs.Int,2));
        var invoked=Cs.Call(Cs.Member(Cs.Id("Math"),"Abs"),Cs.Literal(-1));
        var doc=Cs.Document().Using("System").Class("C").Method<int>("M").Expression(invoked).End()
            .Method(Cs.Type("System.Threading.Tasks.Task").Generic(Cs.Int),"N").Async().Body(Cs.Return(invoked.Await())).End().End().Build();
        Assert.Contains("=> Math.Abs(-1);",doc.Render()); Assert.Contains("return await Math.Abs(-1);",doc.Render());
        var equalTextDifferentIntent=new CsDocument(){Types=new[]{new CsTypeDeclaration(TypeKind.Class,"C"){Members=new CsMember[]{new CsField(Cs.RawType("int"),"F")}}}};
        var structured=equalTextDifferentIntent with {Types=new[]{equalTextDifferentIntent.Types[0] with {Members=new CsMember[]{new CsField(Cs.Int,"F")}}}};
        Assert.Equal(structured.Render(),equalTextDifferentIntent.Render()); Assert.NotEqual(structured,equalTextDifferentIntent);
    }

    [Fact(DisplayName =
        "[SEC][UC-002] " +
        "Neemle.CSharpComposer.Tests.AdditionalTests." +
        "Reflection_qualification_survives_System_shadow_and_raw_literals_preserve_runtime_values")]
    public void Reflection_qualification_survives_System_shadow_and_raw_literals_preserve_runtime_values()
    {
        var doc=Cs.Document().Namespace("Example").Class("System").End()
            .Class("C").Public().Field(Cs.Type<DateTime>(),"Date").Public().End()
            .Add(Cs.RawMember("public static string Text => @\"first\nsecond\";" )).End().Build();
        var source=doc.Render();         using var stream=new MemoryStream();         Assert.Contains("global::System.DateTime Date",source);
        Assert.Equal("SpecialFolder",Cs.Type<Environment.SpecialFolder>().Name);
    }

    [Fact(DisplayName =
        "[SEC][UC-002] " +
        "Neemle.CSharpComposer.Tests.AdditionalTests." +
        "Supported_unicode_and_at_prefix_names_are_escaped_by_segment")]
    public void Supported_unicode_and_at_prefix_names_are_escaped_by_segment()
    {
        var doc=Cs.Document().Class("@class").Field<int>("_a1\u0301\u200c").End().End().Build();
Assert.Contains("class @class",doc.Render());
        Assert.Contains(new CsDocument(){Types=new[]{new CsTypeDeclaration(TypeKind.Class,"@")} }.Validate(),d=>d.Code=="GEN003");
    }

    [Fact(DisplayName =
        "[SEC][UC-003] " +
        "Neemle.CSharpComposer.Tests.AdditionalTests." +
        "Corrupted_cycle_fails_safely_even_if_immutability_is_bypassed_with_reflection")]
    public void Corrupted_cycle_fails_safely_even_if_immutability_is_bypassed_with_reflection()
    {
        var cycle=Cs.Int.Array(); typeof(CsType).GetProperty(nameof(CsType.Element))!.SetValue(cycle,cycle);
        var doc=Cs.Document().Class("C").Field(cycle,"Field").End().End().Build();
        Assert.Contains(doc.Validate(),d=>d.Code=="GEN001"); Assert.Throws<GenValidationException>(()=>doc.Render());
    }
}
