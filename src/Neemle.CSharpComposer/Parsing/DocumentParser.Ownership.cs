using Neemle.CSharpComposer.Model;
namespace Neemle.CSharpComposer.Parsing;

// GENE-29 F5 (AD 84939297 v2 B2-B4): the comment ownership pass. It runs once, after the whole parse, and gives every
// comment token outside raw text, inactive text and directive lines to exactly one node of the result:
// 1. trailing: a comment on the line of the previous significant token P belongs, as a trailing comment, to the
//    outermost node inside E (the innermost node around the comment) that ends at P; a `,` stands for the item before it
//    when no node ends at the comma itself. A comment starting on the line where such a trailing comment ends joins it;
// 2. leading: else to the outermost node inside E that starts at the next significant token N (a directive or inactive
//    text item counts as one), as a leading comment, whatever blank lines lie between;
// 3. dangling: else, when N closes E (`}`, `)`, `]` or the end of the source), to E as a container comment;
// 4. fallback: else as a trailing comment of the outermost node inside E that ends at P, or as a leading comment of
//    E's first child after the comment, or as a container comment of E.
// The comment run that opens a document and is followed by a blank line is the document's leading comments (its file
// preamble, AD B3). Nodes are located by their source spans; a node the parse binds no span to spans its parts.
internal sealed partial class DocumentParser
{
    // `list` roots (a document, a statement sequence) hold every comment between `from` and `to`, and the end of that
    // range closes them; any other root takes the comments before it as leading and those after it as trailing comments.
    CsNode Own(CsNode root, bool list, int from, int to)
    {
        var owned = comments.Where(c => c.Start >= from && c.End <= to).ToArray();
        if (owned.Length == 0) return root;
        marks.Sort();
        var map = new Ownership(this, root, list, from, to);
        int preamble = root is CsDocument { Items.Count: > 0 } ? Preamble(owned) : 0;
        for (int i = 0; i < owned.Length; i++)
            if (i < preamble) map.Put(0, Comment(owned[i], CommentPlacement.Leading));
            else map.Place(owned[i]);
        return map.Attach();
    }

    // AD B3: the number of comments that open the source with only white space before and between them, through the last
    // one a blank line follows (the file preamble: a license header, `// <auto-generated/>`).
    int Preamble(Token[] owned)
    {
        int count = 0;
        for (int i = 0; i < owned.Length && Blank(i == 0 ? 0 : owned[i - 1].End, owned[i].Start); i++)
        {
            int end = owned[i].End, following = end;
            while (following < source.Text.Length && char.IsWhiteSpace(source.Text[following])) following++;
            if (LinesBetween(end, following) > 1) count = i + 1;
        }
        return count;
    }

    sealed class Ownership
    {
        readonly DocumentParser parser;
        readonly List<CsNode> nodes = new();
        readonly List<int> parents = new(), depths = new(), starts = new(), ends = new(), after = new();
        readonly Dictionary<int, List<int>> byStart = new(), byEnd = new();
        readonly List<int> order = new(), stack = new();
        readonly Dictionary<int, List<CsComment>> placed = new();
        int next;
        // The owner, previous token and end of the latest trailing comment (rule 1: a later one on its last line joins it).
        (int Owner, int Previous, int End) trailing = (-1, -2, 0);

        static readonly HashSet<string> Closers = new(StringComparer.Ordinal) { "}", ")", "]", "" };

        internal Ownership(DocumentParser parser, CsNode root, bool list, int from, int to)
        {
            this.parser = parser;
            var walk = new Stack<(CsNode Node, int Parent, int Depth)>();
            walk.Push((root, -1, 0));
            while (walk.Count != 0)
            {
                var (node, parent, depth) = walk.Pop();
                int index = nodes.Count;
                nodes.Add(node); parents.Add(parent); depths.Add(depth); after.Add(index + 1);
                // A node without a span of its own (a wrapper the parse builds) spans its parts; one with none, nothing.
                starts.Add(node.SyntaxPosition?.Offset ?? int.MaxValue); ends.Add(node.SyntaxPosition?.End ?? -1);
                var children = node.Children;
                for (int i = children.Count - 1; i >= 0; i--)
                    if (children[i] is not (CsComment or CsSyntaxTrivia)) walk.Push((children[i], index, depth + 1));
            }
            // Pre-order: a node's subtree is the run of indexes after it, which ends where its last child's ends.
            for (int i = nodes.Count - 1; i > 0; i--)
            {
                int parent = parents[i];
                after[parent] = Math.Max(after[parent], after[i]);
                starts[parent] = Math.Min(starts[parent], starts[i]);
                ends[parent] = Math.Max(ends[parent], ends[i]);
            }
            // A list root holds the whole range from its first character, so it is around every comment from the start.
            if (list) { starts[0] = from; ends[0] = to; stack.Add(0); }
            for (int i = list ? 1 : 0; i < nodes.Count; i++)
            {
                order.Add(i);
                Add(byStart, starts[i], i);
                Add(byEnd, ends[i], i);
            }
            order.Sort((a, b) => (starts[a], -ends[a], depths[a]).CompareTo((starts[b], -ends[b], depths[b])));
        }

        // Pre-order visits an ancestor first, so each list starts with the outermost node.
        static void Add(Dictionary<int, List<int>> index, int offset, int node)
        {
            if (!index.TryGetValue(offset, out var at)) index[offset] = at = new();
            at.Add(node);
        }

        internal void Place(Token comment)
        {
            // E: the innermost node around the comment (comments come in source order, so one sweep finds each).
            while (next < order.Count && starts[order[next]] < comment.Start)
            {
                int node = order[next++];
                while (stack.Count != 0 && ends[stack[^1]] <= starts[node]) stack.RemoveAt(stack.Count - 1);
                stack.Add(node);
            }
            while (stack.Count != 0 && ends[stack[^1]] <= comment.Start) stack.RemoveAt(stack.Count - 1);
            var tokens = parser.tokens;
            int following = Following(tokens, comment.End), previous = following - 1;
            if (stack.Count == 0)
            {
                // Outside a single-node root: before it, a leading comment; after it, a trailing one.
                Put(0, parser.Comment(comment, starts[0] >= comment.End ? CommentPlacement.Leading : CommentPlacement.Trailing));
                return;
            }
            int e = stack[^1];
            // Raw text and its comments are one opaque unit (AD C4).
            if (nodes[e] is CsRaw or CsRawMember or CsStatement { Kind: StatementKind.Raw }) return;
            // Every node that starts at N or ends at P lies inside E, so the first one indexed there is the outermost.
            bool sameLine = previous >= 0 && parser.LinesBetween(tokens[previous].End, comment.Start) == 0;
            int owner = previous == trailing.Previous && parser.LinesBetween(trailing.End, comment.Start) == 0 ? trailing.Owner :
                sameLine ? Ending(tokens, previous) : -1;
            if (owner >= 0)
            {
                trailing = (owner, previous, comment.End);
                Put(owner, parser.Comment(comment, CommentPlacement.Trailing));
                return;
            }
            // N: the next token, or a directive or inactive text item before it.
            int mark = Below(parser.marks, comment.End);
            owner = Outermost(byStart, Math.Min(tokens[following].Start, mark < parser.marks.Count ? parser.marks[mark] : int.MaxValue));
            if (owner >= 0) { Put(owner, parser.Comment(comment, CommentPlacement.Leading)); return; }
            if (Closers.Contains(tokens[following].Text)) { Put(e, parser.Comment(comment, CommentPlacement.Container)); return; }
            owner = Ending(tokens, previous);
            if (owner >= 0) { Put(owner, parser.Comment(comment, CommentPlacement.Trailing)); return; }
            // E's first child after the comment, else E itself.
            owner = e;
            for (int child = e + 1, first = int.MaxValue; child < after[e]; child = after[child])
                if (starts[child] >= comment.End && starts[child] < first) (owner, first) = (child, starts[child]);
            Put(owner, parser.Comment(comment, owner == e ? CommentPlacement.Container : CommentPlacement.Leading));
        }

        // The index of the first significant token at or after `offset` (the end token, at worst).
        static int Following(List<Token> tokens, int offset)
        {
            int low = 0, high = tokens.Count - 1;
            while (low < high) { int middle = (low + high) >> 1; if (tokens[middle].Start < offset) low = middle + 1; else high = middle; }
            return low;
        }

        // The outermost node that ends at token `previous`, or, when that is a `,` no node ends at, at the token before it.
        int Ending(List<Token> tokens, int previous)
        {
            int owner = Outermost(byEnd, tokens[previous].End);
            return owner < 0 && tokens[previous].Text == "," ? Outermost(byEnd, tokens[previous - 1].End) : owner;
        }

        static int Outermost(Dictionary<int, List<int>> index, int offset) => index.TryGetValue(offset, out var found) ? found[0] : -1;

        internal void Put(int owner, CsComment comment)
        {
            if (!placed.TryGetValue(owner, out var at)) placed[owner] = at = new();
            at.Add(comment);
        }

        // The result with each placed comment on its owner, after the comments the owner already holds (a directive's own).
        internal CsNode Attach()
        {
            var targets = new Dictionary<CsNode, List<CsComment>>(ReferenceEqualityComparer.Instance);
            var path = new HashSet<CsNode>(ReferenceEqualityComparer.Instance);
            foreach (var (owner, found) in placed)
            {
                targets[nodes[owner]] = found;
                for (int at = owner; at >= 0 && path.Add(nodes[at]); at = parents[at]) { }
            }
            return Spine.Rewrite(nodes[0], path.Contains, (original, rebuilt) => targets.TryGetValue(original, out var found)
                ? rebuilt with { Comments = new(rebuilt.Comments.Concat(found)) } : rebuilt);
        }
    }

    // A parsed comment (AD B4): a single-line comment as written; a comment over several lines with its line breaks as
    // "\n" and each later line without the indentation of the line the comment starts on (a `///` run: without any
    // indentation before its `///`), so that the formatter writes it at any indentation and it reads back the same. The
    // formatter writes those lines at the indentation of the line it writes the comment on, so a comment after code on its
    // line keeps its later lines where they were relative to that line.
    CsComment Comment(Token token, CommentPlacement placement)
    {
        string text = token.Text;
        if (text.AsSpan().IndexOfAny('\r', '\n') >= 0)
        {
            int column = 0;
            for (int at = LineStart(token.Start); source.Text[at] is ' ' or '\t'; at++) column++;
            bool documentation = text.StartsWith("///", StringComparison.Ordinal);
            var lines = text.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n').Split('\n');
            for (int i = 1; i < lines.Length; i++)
            {
                int remove = 0;
                while (remove < lines[i].Length && (documentation || remove < column) && lines[i][remove] is ' ' or '\t') remove++;
                lines[i] = lines[i][remove..];
            }
            text = string.Join("\n", lines);
        }
        var comment = new CsComment(text,
            text.StartsWith("///", StringComparison.Ordinal) || text.StartsWith("/**", StringComparison.Ordinal)
                ? CommentKind.Documentation : text.StartsWith("/*", StringComparison.Ordinal)
                    ? CommentKind.Block : CommentKind.Line, placement);
        if (comment.Kind == CommentKind.Documentation) comment = DocumentationParser.Parse(comment, version);
        return comment with { SyntaxPosition = new(syntaxIdentity, token.Start, token.End) };
    }
}
